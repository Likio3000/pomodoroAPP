export const messages = { es, en };
export type Values = Record<string, string | number>;
export function translate(language: Language, key: MessageKey, values: Values = {}): string {
  return messages[language][key].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? `{${name}}`),
  );
}
export class UserError extends Error {
  constructor(
    public readonly key: MessageKey,
    public readonly values: Values = {},
  ) {
    super(translate('es', key, values));
  }
}
export function errorText(language: Language, error: unknown): string {
  if (!(error instanceof UserError)) return translate(language, 'storageError');
  const values = { ...error.values };
  if (error.key === 'settingRange') {
    const field = String(values.field);
    values.field = translate(
      language,
      field === 'goal' ? 'dailyGoal' : (`mode.${field}` as MessageKey),
    );
  }
  return translate(language, error.key, values);
}
